// Builds the conformance suite of SPEC 17.2 from the cases in cases.mjs:
// the documents, the expected results of the reference implementation (the
// `@openavatar/core` package), the geometry vectors and the reference renders
// (`@openavatar/three`, the renders in a headless browser). Run from openavatar/:
//
//   node conformance/tools/build.mjs              everything
//   node conformance/tools/build.mjs --no-renders documents and expectations only
import fs from 'node:fs';
import path from 'node:path';
import { normalize, parse, validate, resolveBehavior, stringify, OpenAvatarError } from '@openavatar/core';
import { RENDER, REPAIR, REJECT, BEHAVIOR, covers } from './cases.mjs';
import { geometryVectors } from './geometry.mjs';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const examples = path.resolve(root, '../examples');
const renders = !process.argv.includes('--no-renders');
const out = (rel, text) => { const f = path.join(root, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, text); };
for (const dir of ['render', 'geometry', 'repair', 'reject', 'behavior', ...(renders ? ['renders'] : [])]) fs.rmSync(path.join(root, dir), { recursive: true, force: true });

const manifest = { openavatar: '0.1', $comment: 'The OpenAvatar 0.1 conformance suite (SPEC 17.2). Generated by tools/build.mjs; see README.md.', render: [], repair: [], reject: [], behavior: 'behavior/cases.json' };

// Render cases: the suite's own documents, then the examples.
const renderDocs = [];
for (const c of RENDER) {
  const v = validate(c.document);
  if (!v.valid) throw new Error(`${c.id} is not valid: ${JSON.stringify(v.errors)}`);
  out(`render/${c.id}.openavatar`, stringify(c.document));
  renderDocs.push({ id: c.id, document: c.document, cells: c.cells });
  manifest.render.push({ id: c.id, file: `render/${c.id}.openavatar`, geometry: `geometry/${c.id}.json`, render: `renders/${c.id}.webp`, shows: c.shows, covers: covers(c.document) });
}
for (const f of fs.readdirSync(examples).filter(f => f.endsWith('.openavatar')).sort()) {
  const id = `example-${f.replace('.openavatar', '')}`, document = JSON.parse(fs.readFileSync(path.join(examples, f), 'utf8'));
  renderDocs.push({ id, document, sheet: true });
  manifest.render.push({ id, file: `../examples/${f}`, geometry: `geometry/${id}.json`, render: `renders/${id}.webp`, shows: document.meta?.description || document.name, covers: covers(document) });
}

// Geometry vectors: the fields and placements of each render case, one array of numbers to a line.
const lines = o => JSON.stringify(o, null, 2).replace(/\[\s+([-\d.e,\s]+?)\s+\]/g, (_, inner) => `[${inner.trim().split(/,\s*/).join(', ')}]`) + '\n';
for (const d of renderDocs) out(`geometry/${d.id}.json`, lines(geometryVectors(d.document, d.id)));

// Repair cases: the input, and the document a reader ends up with.
for (const c of REPAIR) {
  const text = typeof c.input === 'string' ? c.input : JSON.stringify(c.input, null, 2) + '\n';
  out(`repair/${c.id}.openavatar`, text);
  const { document, repairs } = parse(text);
  if (!repairs.length !== !!c.kept) throw new Error(`${c.id}: ${repairs.length} repairs`);
  out(`repair/${c.id}.expected.openavatar`, stringify(document));
  manifest.repair.push({ id: c.id, file: `repair/${c.id}.openavatar`, expected: `repair/${c.id}.expected.openavatar`, repairs: repairs.map(r => r.path), checks: c.checks });
}

// Reject cases: what a reader must refuse, and why.
for (const c of REJECT) {
  const text = typeof c.input === 'string' ? c.input : JSON.stringify(c.input);
  out(`reject/${c.id}.openavatar`, text);
  let code = null;
  try { parse(text); } catch (e) { if (e instanceof OpenAvatarError) code = e.code; else throw e; }
  if (code !== c.code) throw new Error(`${c.id}: expected ${c.code}, got ${code}`);
  manifest.reject.push({ id: c.id, file: `reject/${c.id}.openavatar`, code, because: c.because });
}

// Behavior cases: inputs and the channels every reader must resolve (SPEC 11.3, 13).
const docs = Object.fromEntries(BEHAVIOR.documents.map(d => [d.id, d]));
for (const d of BEHAVIOR.documents) if (d.document) out(`behavior/${d.id}.openavatar`, stringify(d.document));
const cases = BEHAVIOR.cases.map(c => {
  const d = docs[c.document];
  const doc = d.document ?? JSON.parse(fs.readFileSync(path.join(examples, d.example), 'utf8'));
  const r = resolveBehavior(normalize(doc).document, c.input);
  const expected = { expression: r.expression, expressionIntensity: r.expressionIntensity, motion: r.motion, prop: r.prop, effect: r.effect, gaze: r.gaze, quiet: r.quiet };
  return { id: c.id, document: d.document ? `behavior/${d.id}.openavatar` : `../examples/${d.example}`, input: c.input, expected, checks: c.checks };
});
out('behavior/cases.json', JSON.stringify({ $comment: 'For each case, a reader given the document and the input resolves these channels (SPEC 11.3), as a renderer that knows exactly the standard ids of 0.1 does: ids it does not know take their fallbacks (SPEC 13). null means the channel is not set.', cases }, null, 2) + '\n');
out('manifest.json', JSON.stringify(manifest, null, 2) + '\n');
console.log(`${manifest.render.length} render cases with geometry, ${manifest.repair.length} repair, ${manifest.reject.length} reject, ${cases.length} behavior cases`);

if (renders) {
  const { openRenderer, SHEET } = await import('@openavatar/cli');
  const r = await openRenderer();
  try {
    let bytes = 0;
    for (const d of renderDocs) {
      const cells = d.sheet ? SHEET : (d.cells || [{ label: 'front' }, { label: 'three-quarter', view: 35 }]);
      const { image } = await r.sheet(d.document, { cells, cell: d.sheet ? 160 : 192, columns: d.sheet ? 6 : cells.length, format: 'webp', quality: .82 });
      out(`renders/${d.id}.webp`, image); bytes += image.length;
    }
    if (r.warnings.length) throw new Error(`the browser reported errors:\n${r.warnings.join('\n')}`);
    console.log(`${renderDocs.length} renders, ${Math.round(bytes / 1024)} KB`);
  } finally { await r.close(); }
}
